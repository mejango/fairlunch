// Writes the contract's ABI for the site from the Foundry build. Run `forge build` first. `--check` fails on drift.
import { readFileSync, writeFileSync } from 'node:fs'

const artifact = new URL('../../out/FairLunch.sol/FairLunch.json', import.meta.url)
const target = new URL('../src/lib/fair-lunch/abi.ts', import.meta.url)
const abi = JSON.parse(readFileSync(artifact, 'utf8')).abi
const text = `// Generated by scripts/sync-abi.mjs. Do not edit.\nexport const fairLunchAbi = ${JSON.stringify(abi, null, 2)} as const\n`
if (process.argv.includes('--check')) {
  if (readFileSync(target, 'utf8') !== text) {
    console.error('src/lib/fair-lunch/abi.ts is out of date. Run npm run abi:sync.')
    process.exit(1)
  }
} else writeFileSync(target, text)
